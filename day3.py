# Number classification program.
# for loop
for i in range(1,11):
    print(i)
# while loop
i = 1
while i <= 10:
    print(i)
    i += 1




# pattern program using star
for i in range(1,6):
    print("*" * i)


# pattern program using numbers
for i in range(1,6):
    for j in range(1,i+1):
        print(j,end="")
    print()